import { performance } from "node:perf_hooks";
import { loadZig, loadRust, genEntries as gen, flatten, framedBlocks } from "./loader.mjs";

const rust = await loadRust();
const z = await loadZig("./engine_fast.wasm");
const ex = z.ex;
const put = (u8) => { const p = ex.input_ptr(u8.length); new Uint8Array(ex.memory.buffer).set(u8, p); return p; };
const med = (fn, reps = 15) => { const t = []; for (let i = 0; i < reps; i++) { const a = performance.now(); fn(); t.push(performance.now() - a); } t.sort((x, y) => x - y); return t[reps >> 1].toFixed(2); };
const cmp = (a, b) => { const n = Math.min(a.length, b.length); for (let i = 0; i < n; i++) if (a[i] !== b[i]) return a[i] - b[i]; return a.length - b.length; };
const big = gen(50000, 11);
const sorted = big.slice().sort((a, b) => cmp(a.key, b.key));
const f1 = flatten(big), f2 = flatten(sorted);
const zenc = (flat, lz4) => { const p = put(flat); ex.encode_sst(p, flat.length, lz4 ? 1 : 0); };
console.log("zig encode raw, random order :", med(() => zenc(f1, false)), "ms");
console.log("zig encode raw, pre-sorted   :", med(() => zenc(f2, false)), "ms   (difference = std.mem.sort cost)");
console.log("zig input copy only          :", med(() => put(f1)), "ms");
console.log(`rust (${rust.abi}) encode raw total :`, med(() => rust.encodeEntries(big, false)), "ms");
console.log(`rust (${rust.abi}) encode of pre-sorted:`, med(() => rust.encodeEntries(sorted, false)), "ms");
const blk = framedBlocks(rust.encodeEntries(big, true))[0];
const size = new DataView(blk.buffer, blk.byteOffset).getUint32(0, true); const body = blk.subarray(4);
console.log(`block: ${blk.length} B compressed -> ${size} B`);
const rustLz4 = rust.abi === "flat" ? () => { const p = rust.ex.input_ptr(body.length); new Uint8Array(rust.ex.memory.buffer).set(body, p); rust.ex.lz4_decompress(p, body.length, size); } : () => rust.lz4(body, size);
console.log(`rust (${rust.abi}) lz4_decompress x2000:`, med(() => { for (let i = 0; i < 2000; i++) rustLz4(); }), "ms");
console.log("zig  lz4_decompress x2000    :", med(() => { for (let i = 0; i < 2000; i++) { const p = put(body); ex.lz4_decompress(p, body.length, size); } }), "ms");
console.log("zig  input copy x2000        :", med(() => { for (let i = 0; i < 2000; i++) put(body); }), "ms");
