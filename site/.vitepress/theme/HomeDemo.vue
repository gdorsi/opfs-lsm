<script setup lang="ts">
import { useData, withBase } from "vitepress";
import { computed, nextTick, onBeforeUnmount, onMounted, ref } from "vue";

/**
 * LinearLite in a browser frame, with the timings it measures under it. The app is the static build of
 * `examples/linearlite-docstore`, served next to the site. It measures itself and posts each timing here
 * (`examples/linearlite-docstore/src/protocol.ts` lists the messages); this component only shows them.
 *
 * On a touch screen or a narrow one the frame is a preview the page scrolls past: the app inside it takes no input,
 * so a swipe over it scrolls the page, not the app's list. Tapping it opens the app full screen.
 */
const SOURCE = "linearlite-demo";
const DB = "linearlite-docstore";

type Host = "restarted" | "alive" | "unknown";

const { frontmatter } = useData();
const countLabel = computed(() => String(frontmatter.value.demo.count));
const count = computed(() => Number(countLabel.value.replace(/\D/g, "")));
const source = computed(() => String(frontmatter.value.demo.source));
/** Unset until this page is idle, so the app does not share the main thread with the page's own start. */
const src = ref<string>();

const frame = ref<HTMLIFrameElement>();
const state = ref<"waiting" | "loading" | "generating" | "ready" | "failed">("waiting");
const written = ref<{ count: number; writeMs: number }>();
const opened = ref<{ ms: number; host: Host }>();
const filtered = ref<{ label: string; rowsMs: number }>();
/** The last timing the app sent, shown in the full-screen bar while the visitor uses the app. */
const latest = ref<string>();
const failure = ref("");
let autoGenerated = false;

const ms = (n: number) => (n < 1000 ? `${Math.round(n)} ms` : `${(n / 1000).toFixed(2)} s`);
const n = (x: number) => Math.round(x).toLocaleString("en-US");

const post = (message: Record<string, unknown>) =>
  frame.value?.contentWindow?.postMessage({ source: SOURCE, ...message }, location.origin);

function onMessage(e: MessageEvent) {
  if (e.source !== frame.value?.contentWindow || e.data?.source !== SOURCE) return;
  const m = e.data;
  if (m.type === "opened") {
    state.value = m.issues > 0 ? "ready" : "generating";
    // Generate on the first open of the page only. After the app's own Delete, its Generate button does it.
    if (m.issues === 0 && !autoGenerated) post({ type: "generate", count: count.value });
    autoGenerated = true;
  } else if (m.type === "progress") state.value = "generating";
  else if (m.type === "generated") {
    state.value = "ready";
    written.value = { count: m.count, writeMs: m.writeMs };
    latest.value = `Wrote ${n(m.count)} issues in ${ms(m.writeMs)}`;
  } else if (m.type === "first-rows") {
    opened.value = { ms: m.ms, host: m.host };
    latest.value = `Opened in ${ms(m.ms)}`;
  } else if (m.type === "filter") {
    filtered.value = m;
    latest.value = `Filtered in ${ms(m.rowsMs)}`;
  } else if (m.type === "deleted") reload(false);
  else if (m.type === "failed") {
    state.value = "failed";
    failure.value = m.message;
  }
}

function reload(timed = true) {
  state.value = "loading";
  opened.value = undefined;
  filtered.value = undefined;
  latest.value = undefined;
  if (!timed) written.value = undefined;
  frame.value?.contentWindow?.location.reload();
}

/**
 * Calls `then` once the page has loaded and the browser reports a whole idle period, or after three seconds. The
 * frame shares this page's main thread, so an app loaded sooner would be timed while the page mounts its figures.
 */
function whenIdle(then: () => void) {
  const deadline = performance.now() + 3000;
  const wait = () => {
    if (typeof requestIdleCallback !== "function") return void setTimeout(then, 300);
    requestIdleCallback((idle) => (idle.timeRemaining() >= 40 || performance.now() > deadline ? then() : wait()), { timeout: 1000 });
  };
  if (document.readyState === "complete") wait();
  else addEventListener("load", wait, { once: true });
}

/*
 * Preview and full screen. Moving the iframe in the document would reload the app, so full screen restyles its box
 * to cover the viewport instead. The box it leaves keeps its height, so the page under it doesn't move. Opening grows
 * from the preview's rectangle (a clip-path), and closing shrinks back into it.
 */
const compact = ref(false);
const expanded = ref(false);
const view = ref<HTMLDivElement>();
const screen = ref<HTMLDivElement>();
const openButton = ref<HTMLButtonElement>();
const closeButton = ref<HTMLButtonElement>();
const EASE = "cubic-bezier(0.32, 0.72, 0, 1)";
const FULL = "inset(0px 0px 0px 0px round 0px)";
const insetOf = (r: DOMRect) =>
  `inset(${r.top}px ${innerWidth - r.right}px ${innerHeight - r.bottom}px ${r.left}px round 14px)`;
let reduced = false;
let morph: Animation | undefined;

const lock = (on: boolean) => {
  document.documentElement.style.overflow = on ? "hidden" : "";
};

async function open() {
  if (expanded.value || !view.value) return;
  const from = insetOf(view.value.getBoundingClientRect());
  expanded.value = true;
  lock(true);
  await nextTick();
  closeButton.value?.focus({ preventScroll: true });
  if (reduced || !screen.value) return;
  morph?.cancel();
  morph = screen.value.animate([{ clipPath: from }, { clipPath: FULL }], { duration: 380, easing: EASE });
}

async function close(animate = true) {
  if (!expanded.value) return;
  if (animate && !reduced && screen.value && view.value) {
    morph?.cancel();
    morph = screen.value.animate([{ clipPath: FULL }, { clipPath: insetOf(view.value.getBoundingClientRect()) }], {
      duration: 280,
      easing: EASE,
      fill: "forwards",
    });
    await morph.finished.catch(() => {});
  }
  expanded.value = false;
  lock(false);
  await nextTick();
  morph?.cancel();
  openButton.value?.focus({ preventScroll: true });
}

const onKey = (e: KeyboardEvent) => {
  if (e.key === "Escape" && expanded.value) close();
};

let media: MediaQueryList | undefined;
const onMedia = () => {
  compact.value = !!media?.matches;
  if (!compact.value) close(false);
};

let mounted = false;
onMounted(() => {
  mounted = true;
  reduced = matchMedia("(prefers-reduced-motion: reduce)").matches;
  media = matchMedia("(max-width: 639px), (pointer: coarse)");
  onMedia();
  media.addEventListener("change", onMedia);
  addEventListener("message", onMessage);
  addEventListener("keydown", onKey);
  whenIdle(() => {
    if (!mounted) return;
    state.value = "loading";
    src.value = withBase(`/demo/index.html?db=${DB}&count=${count.value}`);
  });
});
onBeforeUnmount(() => {
  mounted = false;
  media?.removeEventListener("change", onMedia);
  removeEventListener("message", onMessage);
  removeEventListener("keydown", onKey);
  if (expanded.value) lock(false);
});

const starting = computed(() => state.value === "waiting" || state.value === "loading");

/** What restarted with the app. A SharedWorker that restarted makes the open the slowest one. */
const HOSTS: Record<Host, string> = {
  restarted: "cold, SharedWorker restarted",
  alive: "SharedWorker still running",
  unknown: "page restarted",
};
</script>

<template>
  <div class="demo" :data-state="state" :data-compact="compact ? '' : undefined">
    <div class="demo-bar">
      <span class="demo-dots" aria-hidden="true"><i /><i /><i /></span>
      <a class="demo-address" :href="source" target="_blank" rel="noreferrer" title="The app's source on GitHub">
        LinearLite · {{ countLabel }} issues
      </a>
      <button type="button" class="demo-reload" :disabled="state !== 'ready'" @click="reload()">
        <svg viewBox="0 0 24 24" aria-hidden="true"><path d="M20 11a8 8 0 1 0-2.3 5.7" /><path d="M20 4v7h-7" /></svg>
        <span>Reload and time it</span>
      </button>
    </div>

    <div ref="view" class="demo-view">
      <div
        ref="screen"
        class="demo-screen"
        :data-expanded="expanded ? '' : undefined"
        :role="expanded ? 'dialog' : undefined"
        :aria-modal="expanded ? 'true' : undefined"
        :aria-label="expanded ? 'LinearLite, full screen' : undefined"
      >
        <div v-show="expanded" class="demo-screen-bar">
          <button ref="closeButton" type="button" class="demo-screen-button" @click="close()">
            <svg viewBox="0 0 24 24" aria-hidden="true"><path d="M6 9l6 6 6-6" /></svg>
            Close
          </button>
          <Transition name="demo-value" mode="out-in">
            <span :key="latest ?? 'title'" class="demo-latest" aria-live="polite">{{ latest ?? `LinearLite · ${countLabel} issues` }}</span>
          </Transition>
          <button type="button" class="demo-screen-button demo-screen-reload" :disabled="state !== 'ready'" aria-label="Reload and time it" @click="reload()">
            <svg viewBox="0 0 24 24" aria-hidden="true"><path d="M20 11a8 8 0 1 0-2.3 5.7" /><path d="M20 4v7h-7" /></svg>
          </button>
        </div>

        <iframe
          ref="frame"
          class="demo-frame"
          :src="src"
          :inert="compact && !expanded ? '' : undefined"
          title="LinearLite, an issue tracker running on opfs-lsm with no server"
        />

        <!-- The preview's cover: a swipe on it scrolls the page, a tap opens the app. -->
        <button
          v-if="compact && !expanded"
          ref="openButton"
          type="button"
          class="demo-open"
          :disabled="starting"
          :aria-label="starting ? 'Starting the app' : 'Open the app full screen'"
          @click="open"
        >
          <span class="demo-open-pill">
            <template v-if="starting">Starting the app</template>
            <template v-else>
              <svg viewBox="0 0 24 24" aria-hidden="true"><path d="M15 3h6v6" /><path d="M9 21H3v-6" /><path d="M21 3l-7 7" /><path d="M3 21l7-7" /></svg>
              Open the app
            </template>
          </span>
        </button>

        <Transition name="demo-status">
          <div v-if="!compact && starting" class="demo-status" role="status">Starting the app</div>
        </Transition>
      </div>
    </div>

    <dl class="demo-timings" aria-live="polite">
      <div>
        <dt><span class="demo-long">Write {{ countLabel }} issues</span><span class="demo-short">Write {{ countLabel }}</span></dt>
        <dd>
          <Transition name="demo-value" mode="out-in">
            <b v-if="written" :key="written.writeMs">{{ ms(written.writeMs) }}</b>
            <b v-else-if="opened" key="stored" class="demo-none">Already stored</b>
            <b v-else key="none" class="demo-none">–</b>
          </Transition>
        </dd>
      </div>
      <div>
        <dt><span class="demo-long">Open and read the first rows</span><span class="demo-short">Open</span></dt>
        <dd>
          <Transition name="demo-value" mode="out-in">
            <b v-if="opened" :key="opened.ms">{{ ms(opened.ms) }} <span class="demo-long">{{ HOSTS[opened.host] }}</span></b>
            <b v-else key="none" class="demo-none">–</b>
          </Transition>
        </dd>
      </div>
      <div>
        <dt><span class="demo-long">Filter the list</span><span class="demo-short">Filter</span></dt>
        <dd>
          <Transition name="demo-value" mode="out-in">
            <b v-if="filtered" :key="filtered.rowsMs">{{ ms(filtered.rowsMs) }} <span class="demo-long">{{ filtered.label }}</span></b>
            <b v-else key="none" class="demo-none">Try a filter</b>
          </Transition>
        </dd>
      </div>
    </dl>
    <p v-if="state === 'failed'" class="demo-failed" role="alert">The demo could not run in this browser: {{ failure }}</p>
  </div>
</template>
